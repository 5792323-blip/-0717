# time_exit.py — 时间退出
# 功能: 持仓超过一定K线数还亏损 -> 清仓换股
# 避免"拿了太久还不赚钱"的僵局

def 检查(持仓盈亏比例, 持有K线数=None, 最大持仓K线数=80, 亏损阈值=None, **kwargs):
    """
    检查是否需要时间退出

    传入:
        持仓盈亏比例  - 当前盈亏比例
        持有K线数     - 已持仓的K线数量
        最大持仓K线数 - 最大容忍K线数（默认80）
        亏损阈值      - 亏损超过此值才触发（默认-8%）

    传出:
        字典: {"触发": True/False, "原因": "..."}
    """
    if 亏损阈值 is None:
        亏损阈值 = kwargs.get("亏损触发", -0.08)

    if 持有K线数 is None or 持仓盈亏比例 is None:
        return {"触发": False}

    if 持有K线数 >= 最大持仓K线数 and 持仓盈亏比例 <= 亏损阈值:
        return {
            "触发": True,
            "原因": f"时间退出: 持有{持有K线数}根K线(>={最大持仓K线数})亏损{持仓盈亏比例*100:.1f}%(<={亏损阈值*100:.0f}%)"
        }

    return {"触发": False}


if __name__ == "__main__":
    print("=" * 40)
    print("时间退出 — 自检测试")
    print("=" * 40)
    测试集 = [
        (100, -0.10, True),
        (50,  -0.10, False),
        (100, -0.05, False),
        (80,  -0.08, True),
        (90,  -0.15, True),
    ]
    for k线数, 盈亏, 预期 in 测试集:
        结果 = 检查(盈亏, 持有K线数=k线数)
        实际 = 结果["触发"]
        print(f"  持有{k线数:>3}根 盈亏{盈亏*100:+.0f}% -> {'触发' if 实际 else '不触发'} {'OK' if 实际 == 预期 else 'FAIL'}")

    print("OK time_exit 自检完成")
