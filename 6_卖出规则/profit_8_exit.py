# profit_8_exit.py — 盈利8%平仓
# 功能: 持仓盈利达到固定阈值后直接全仓平仓。


def 检查(持仓盈亏比例, 盈利阈值=0.08, **kwargs):
    """
    检查是否达到固定盈利平仓条件。

    传入:
        持仓盈亏比例 - 当前这笔交易的净盈亏比例，0.08 表示盈利 8%
        盈利阈值     - 触发平仓的盈利比例，默认 8%

    传出:
        字典: {"触发": True/False, "卖出比例": 1.0, "原因": "..."}
    """
    if 持仓盈亏比例 is None:
        return {"触发": False}

    if 持仓盈亏比例 >= 盈利阈值:
        return {
            "触发": True,
            "卖出比例": 1.0,
            "原因": f"盈利8%平仓触发: 当前盈利{持仓盈亏比例 * 100:.1f}% >= {盈利阈值 * 100:.1f}%",
        }

    return {"触发": False}
