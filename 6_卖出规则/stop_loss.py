# stop_loss.py — 硬止损
# 功能: 亏损到一定程度立刻砍仓，不犹豫
# 止损宽度 = ATR倍数 (不同股票不同，不搞一刀切)
#
# 用法:
#   from 卖出规则.stop_loss import 检查

def 检查(持仓盈亏比例, 当前ATR, 买入价, 止损倍数=3, **kwargs):
    """
    检查是否需要硬止损
    
    传入:
        持仓盈亏比例  - 当前盈亏比例 (-0.05=亏5%)
        当前ATR      - 当前的ATR值
        买入价        - 买入价格
        止损倍数      - 几倍ATR，默认3
    
    传出:
        字典: {"触发": True/False, "原因": "..."}
    """
    
    if 持仓盈亏比例 is None or 买入价 is None or 买入价 == 0:
        return {"触发": False}
    
    if 当前ATR is None or 当前ATR <= 0:
        当前ATR = 买入价 * 0.02  # 没有ATR时用2%估算
    
    # ATR止损价 = 买入价 - 止损倍数 × ATR
    ATR止损价 = 买入价 - 止损倍数 * 当前ATR
    ATR止损比例 = (买入价 - ATR止损价) / 买入价
    
    # 如果当前亏损已经超过ATR止损比例 → 触发
    if 持仓盈亏比例 <= -ATR止损比例:
        return {
            "触发": True,
            "原因": f"硬止损触发: 亏{持仓盈亏比例*100:.1f}% > {ATR止损比例*100:.1f}% ({止损倍数}×ATR)",
            "止损价": ATR止损价
        }
    
    return {"触发": False}


if __name__ == "__main__":
    print("=" * 40)
    print("硬止损 — 自检测试")
    print("=" * 40)
    
    # 假设: 买入价100元, ATR=3元, 3×ATR止损=91元, 止损比例9%
    测试集 = [
        (-0.03, 3, 100, False),   # 亏3% → 不触发(<9%)
        (-0.08, 3, 100, False),   # 亏8% → 不触发(<9%)
        (-0.10, 3, 100, True),    # 亏10% → 触发(>9%)
        (-0.15, 3, 100, True),    # 亏15% → 触发
        (-0.05, 1, 100, True),    # 亏5%, ATR很小=1 → 止损3% → 触发
    ]
    
    for 盈亏, atr, 价格, 预期 in 测试集:
        结果 = 检查(盈亏, atr, 价格)
        实际 = 结果["触发"]
        是否正确 = "✅" if 实际 == 预期 else "❌"
        print(f"  亏{盈亏*100:+.0f}% ATR={atr} 买入价{价格} → {结果['原因'] if 实际 else '不触发'} {是否正确}")
    
    print("\n✅ 硬止损自检完成")
