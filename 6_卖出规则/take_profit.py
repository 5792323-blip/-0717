# take_profit.py — 分批止盈
# 功能: 赚到一定比例就分批卖出，锁定利润
# 三级止盈: 赚5%卖1/3 → 赚10%再卖1/3 → 赚20%全清
#
# 用法:
#   from 卖出规则.take_profit import 检查

def 检查(持仓盈亏比例, 当前持仓比例, **kwargs):
    """
    检查是否需要分批止盈
    
    传入:
        持仓盈亏比例  - 当前这笔交易的盈亏比例 (0.05=赚5%)
        当前持仓比例  - 当前还持有多少 (1.0=全仓, 0.5=半仓)
    
    传出:
        字典: {"触发": True/False, "卖出比例": 小数, "原因": "..."}
    """
    
    if 持仓盈亏比例 is None:
        return {"触发": False}
    
    # 第一目标: 赚5%卖1/3 (如果还有2/3以上仓位)
    if 持仓盈亏比例 >= 0.20 and 当前持仓比例 > 0.1:
        return {"触发": True, "卖出比例": 当前持仓比例, "原因": f"分批止盈第三档(赚{持仓盈亏比例*100:.1f}>20%)全清"}
    
    if 持仓盈亏比例 >= 0.10 and 当前持仓比例 > 0.5:
        return {"触发": True, "卖出比例": 当前持仓比例 / 2, "原因": f"分批止盈第二档(赚{持仓盈亏比例*100:.1f}%)卖一半"}
    
    if 持仓盈亏比例 >= 0.05 and 当前持仓比例 > 0.8:
        return {"触发": True, "卖出比例": 当前持仓比例 / 3, "原因": f"分批止盈第一档(赚{持仓盈亏比例*100:.1f}%)卖1/3"}
    
    return {"触发": False}


if __name__ == "__main__":
    print("=" * 40)
    print("分批止盈 — 自检测试")
    print("=" * 40)
    
    测试集 = [
        (0.03, 1.0, False),   # 赚3% → 不触发
        (0.06, 1.0, True),    # 赚6% → 卖1/3
        (0.12, 0.67, True),   # 赚12% 还有2/3 → 卖一半
        (0.22, 0.33, True),   # 赚22% 还有1/3 → 全清
        (-0.05, 1.0, False),  # 亏5% → 不触发(止盈不管亏损)
    ]
    
    for 盈亏, 持仓, 预期 in 测试集:
        结果 = 检查(盈亏, 持仓)
        实际 = 结果["触发"]
        是否正确 = "✅" if 实际 == 预期 else "❌"
        print(f"  盈亏{盈亏*100:+.0f}% 持仓{持仓:.0%} → {结果['原因'] if 实际 else '不触发'} {是否正确}")
    
    print("\n✅ 分批止盈自检完成")
