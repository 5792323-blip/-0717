# fixed_stop_loss.py — 固定比例硬止损
#
# 与已有 stop_loss（ATR硬止损）并列，便于分别做消融测试。默认关闭。


def 检查(持仓盈亏比例, 买入价, 固定止损比例=0.08, **kwargs):
    try:
        买入价 = float(买入价)
        盈亏 = float(持仓盈亏比例)
        比例 = abs(float(固定止损比例))
    except (TypeError, ValueError):
        return {"触发": False, "原因": "缺少有效价格、盈亏或止损比例"}

    if 买入价 <= 0 or 比例 <= 0 or 比例 >= 1:
        return {"触发": False, "原因": "价格或固定止损比例无效"}

    止损价 = 买入价 * (1 - 比例)
    触发 = 盈亏 <= -比例
    return {
        "触发": 触发,
        "原因": f"固定比例硬止损: 当前净盈亏{盈亏:.2%}，止损线{止损价:.2f}（-{比例:.2%}）",
        "止损价": 止损价,
        "固定止损比例": 比例,
    }
