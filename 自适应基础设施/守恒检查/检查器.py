"""不修改账户的守恒检查工具。"""


def 检查资金守恒(现金前, 现金后, 净现金变化, 容差=1e-6):
    差异 = float(现金后) - float(现金前) - float(净现金变化)
    return {"通过": abs(差异) <= 容差, "差异": 差异}


def 检查持仓守恒(持仓前, 持仓后, 买入数量, 卖出数量):
    预期 = int(持仓前) + int(买入数量) - int(卖出数量)
    return {"通过": int(持仓后) == 预期, "预期持仓": 预期, "实际持仓": int(持仓后)}


def 检查非负状态(现金, 持仓):
    return {"通过": float(现金) >= -1e-6 and int(持仓) >= 0,
            "现金非负": float(现金) >= -1e-6, "持仓非负": int(持仓) >= 0}

