#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# signal_scorer.py — 信号质量评分 (独立小程序)
# 综合信号类型+大盘+背离+波动率计算最终质量分

from 因子模块.因子基类 import 因子基类

class 信号质量评分(因子基类):
    def __init__(self, 参数=None):
        super().__init__(参数)
        self.名称 = "信号质量评分"
        self.基础分 = {
            "RSI上穿20": self.参数.get('基础分_上穿20', 0.7),
            "RSI上穿30": self.参数.get('基础分_上穿30', 0.5),
            "RSI上穿均线": self.参数.get('基础分_上穿均线', 0.6),
            "RSI上穿70": self.参数.get('基础分_上穿70', 0.4),
        }
    
    def 买入前检查(self, K线数据, 全局状态) -> dict:
        信号类型 = 全局状态.get('哨兵价形成类型', '') if 全局状态 else ''
        基础分 = self.基础分.get(信号类型, 0.5)
        
        # 大盘调整
        大盘 = 全局状态.get('大盘状态', '震荡模式') if 全局状态 else '震荡模式'
        大盘系数 = {"进攻模式": 1.2, "震荡模式": 1.0, "防守模式": 0.6, "收缩模式": 0.4}.get(大盘, 1.0)
        
        # 背离调整
        有顶背离 = 全局状态.get('有顶背离', False) if 全局状态 else False
        有底背离 = 全局状态.get('有底背离', False) if 全局状态 else False
        背离系数 = 0.3 if 有顶背离 else (1.2 if 有底背离 else 1.0)
        
        总分 = 基础分 * 大盘系数 * 背离系数
        总分 = min(总分, 1.0)
        return {"允许买入": True, "质量分调整": 总分, "说明": f"{信号类型}→{总分:.2f}(基础{基础分}×大盘{大盘系数}×背离{背离系数})"}
    
    def 重置(self): pass

if __name__ == "__main__":
    因子 = 信号质量评分()
    print("信号质量评分 自检 OK")
    for 信号 in ["RSI上穿20", "RSI上穿70", "RSI上穿均线"]:
        r = 因子.买入前检查({}, {"哨兵价形成类型": 信号, "大盘状态": "进攻模式", "有顶背离": False, "有底背离": True})
        print(f"  {信号}: {r['说明']}")
