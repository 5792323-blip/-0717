#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# total_control.py — 总仓位控制 (独立小程序)
# 根据大盘状态控制总仓位上限

from 因子模块.因子基类 import 因子基类

class 总仓位控制(因子基类):
    def __init__(self, 参数=None):
        super().__init__(参数)
        self.名称 = "总仓位控制"
        self.上限 = {
            "进攻模式": self.参数.get('进攻模式', 0.98),
            "震荡模式": self.参数.get('震荡模式', 0.50),
            "防守模式": self.参数.get('防守模式', 0.20),
            "收缩模式": self.参数.get('收缩模式', 0.30),
        }
    
    def 买入前检查(self, K线数据, 全局状态) -> dict:
        大盘 = 全局状态.get('大盘状态', '震荡模式') if 全局状态 else '震荡模式'
        当前持仓比例 = 全局状态.get('当前持仓比例', 0) if 全局状态 else 0
        上限 = self.上限.get(大盘, 0.5)
        
        if 当前持仓比例 >= 上限:
            return {"允许买入": False, "质量分调整": 0.5, "说明": f"总仓位{当前持仓比例:.0%}已达上限{上限:.0%}"}
        
        return {"允许买入": True, "质量分调整": 1.0, "说明": f"大盘{大盘}上限{上限:.0%}当前{当前持仓比例:.0%}"}
    
    def 重置(self): pass

if __name__ == "__main__":
    因子 = 总仓位控制()
    print("总仓位控制 自检 OK")
    for 状态 in ["进攻模式", "震荡模式", "防守模式"]:
        r = 因子.买入前检查({}, {"大盘状态": 状态, "当前持仓比例": 0.3})
        print(f"  大盘={状态}, 持仓30%: {r['允许买入']} ({r['说明']})")
    r = 因子.买入前检查({}, {"大盘状态": "震荡模式", "当前持仓比例": 0.6})
    print(f"  大盘=震荡, 持仓60%>上限50%: {r['允许买入']} ({r['说明']})")
