# 因子基类.py — 统一接口定义
# 所有因子小程序必须继承此类

class 因子基类:
    """因子基类 — 定义所有因子的标准接口"""
    
    def __init__(self, 参数=None):
        self.名称 = "未命名因子"
        self.说明 = ""
        self.参数 = 参数 or {}
    
    def 每根K线处理(self, K线数据, 全局状态) -> dict:
        """
        每根K线都会调用（用于状态跟踪）
        
        传入:
            K线数据 - 当前K线数据 (dict)
            全局状态 - 包含当前所有策略状态 (dict)
        
        传出:
            dict: {"结果": str, ...}
        """
        return {"结果": "无操作"}
    
    def 买入前检查(self, K线数据, 全局状态) -> dict:
        """
        买入前检查 — 是否允许买入
        
        传入:
            K线数据 - 当前K线数据
            全局状态 - 策略状态
        
        传出:
            dict: {
                "允许买入": True/False,
                "质量分调整": 0.0~1.0,
                "说明": str
            }
        """
        return {"允许买入": True, "质量分调整": 1.0, "说明": ""}
    
    def 卖出前检查(self, 持仓, K线数据, 全局状态) -> dict:
        """
        卖出前检查 — 是否触发卖出
        
        传入:
            持仓 - 当前持仓信息
            K线数据 - 当前K线数据
            全局状态 - 策略状态
        
        传出:
            dict: {
                "触发卖出": True/False,
                "触发价": float/None,
                "卖出原因": str,
                "说明": str
            }
        """
        return {"触发卖出": False, "触发价": None, "卖出原因": "", "说明": ""}

    def 加仓前检查(self, 持仓, K线数据, 全局状态) -> dict:
        """
        加仓前检查 — 是否触发加仓（默认无动作）

        说明:
            - 用于“已有持仓情况下的二次买入/网格加仓”等扩展逻辑
            - 由执行器在卖出检查之后调用，避免同根同时触发卖出与加仓

        传出:
            dict: {
                "触发加仓": True/False,
                "触发价": float/None,     # 触发边界（例如回撤价位）
                "加仓股数": int/None,      # 建议买入股数（100股整数）
                "加仓原因": str,
                "说明": str
            }
        """
        return {"触发加仓": False, "触发价": None, "加仓股数": None, "加仓原因": "", "说明": ""}
    
    def 重置(self):
        """重置因子状态（每只股票回测开始时调用）"""
        pass
    
    def __repr__(self):
        return f"[因子]{self.名称} - {self.说明}"
