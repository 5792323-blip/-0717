#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# position_sizing.py — 凯利仓位计算 (独立小程序)
# 公式: 基准金额 × 信号质量 × 大盘系数 × 波动率系数

from 因子模块.因子基类 import 因子基类

class 凯利仓位计算(因子基类):
    def __init__(self, 参数=None):
        super().__init__(参数)
        self.名称 = "凯利仓位计算"
        self.基准金额 = self.参数.get('基准金额', 200000)
        self.最大比例 = self.参数.get('最大比例', 0.10)
    
    def 买入前检查(self, K线数据, 全局状态) -> dict:
        信号质量 = 全局状态.get('信号质量', 0.5) if 全局状态 else 0.5
        大盘 = 全局状态.get('大盘状态', '震荡模式') if 全局状态 else '震荡模式'
        总权益 = 全局状态.get('总权益', self.基准金额 / max(self.最大比例, 1e-9)) if 全局状态 else self.基准金额 / max(self.最大比例, 1e-9)
        
        大盘系数 = {"进攻模式": 1.2, "震荡模式": 1.0, "防守模式": 0.5, "收缩模式": 0.3}.get(大盘, 1.0)
        
        # 凯利简化: f = p - q  (p=胜率, q=1-p)
        胜率估计 = 0.4 + 信号质量 * 0.2  # 40%~60%
        凯利比例 = 胜率估计 - (1 - 胜率估计)
        凯利比例 = max(凯利比例, 0)  # 不低于0
        
        建议仓位 = self.基准金额 * 凯利比例 * 大盘系数
        建议仓位 = min(建议仓位, 总权益 * self.最大比例)
        
        return {"允许买入": True, "建议仓位": 建议仓位, "说明": f"凯利={凯利比例:.2f}×大盘={大盘系数:.1f}→{建议仓位:.0f}"}
    
    def 重置(self): pass

if __name__ == "__main__":
    因子 = 凯利仓位计算()
    print("凯利仓位计算 自检 OK")
    for 质量 in [0.3, 0.5, 0.8]:
        r = 因子.买入前检查({}, {"信号质量": 质量, "大盘状态": "进攻模式"})
        print(f"  质量={质量}: {r['说明']}")
