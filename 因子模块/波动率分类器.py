# 波动率分类器.py — 独立小程序
# 方法2: 收益率标准差法计算波动率 → 高/中/低分类 → 建议MA拦截阈值
#
# 规则:
#   高波动(收益率标准差≥3%) → 几乎不拦截 (跌-1.0+涨1.0)
#   中波动(1.5%~3%)        → 适中拦截   (跌-0.5+涨0.5)
#   低波动(<1.5%)          → 严格拦截   (跌-0.3+涨0.3)

import numpy as np
from 因子模块.因子基类 import 因子基类

class 波动率分类器(因子基类):
    def __init__(self, 参数=None):
        super().__init__(参数)
        self.名称 = "波动率分类器"
        self.说明 = "收益率标准差法波动率分类→建议MA拦截阈值"
        self.收益率历史 = []
        self.前收盘 = None
        
        self.高波动阈值 = self.参数.get('高波动阈值', 0.03)
        self.低波动阈值 = self.参数.get('低波动阈值', 0.015)
        self.计算周期 = self.参数.get('计算周期', 20)
        
        self.阈值映射 = self.参数.get('阈值映射', {
            "高波动": {"下跌拦截": -1.0, "上涨拦截": 1.0},
            "中波动": {"下跌拦截": -0.5, "上涨拦截": 0.5},
            "低波动": {"下跌拦截": -0.3, "上涨拦截": 0.3},
        })
        
        self.当前波动率 = 0.0
        self.当前分类 = "中波动"
    
    def 每根K线处理(self, K线数据, 全局状态) -> dict:
        收盘 = K线数据.get('前复权_收盘', None)
        if 收盘 and self.前收盘 is not None and 收盘 != self.前收盘 and self.前收盘 > 0:
            收益率 = (收盘 - self.前收盘) / self.前收盘
            self.收益率历史.append(收益率)
            if len(self.收益率历史) > self.计算周期:
                self.收益率历史.pop(0)
        
        if 收盘:
            self.前收盘 = 收盘
        
        if len(self.收益率历史) >= 10:
            self.当前波动率 = float(np.std(self.收益率历史))
        else:
            self.当前波动率 = 0.0
        
        if self.当前波动率 >= self.高波动阈值:
            self.当前分类 = "高波动"
        elif self.当前波动率 <= self.低波动阈值:
            self.当前分类 = "低波动"
        else:
            self.当前分类 = "中波动"
        
        建议 = self.阈值映射.get(self.当前分类, {})
        
        return {
            "波动率": round(self.当前波动率 * 100, 2),
            "分类": self.当前分类,
            "样本数": len(self.收益率历史),
            "建议_下跌拦截": 建议.get("下跌拦截"),
            "建议_上涨拦截": 建议.get("上涨拦截"),
        }
    
    def 买入前检查(self, K线数据, 全局状态) -> dict:
        建议 = self.阈值映射.get(self.当前分类, {})
        if "波动率分类" not in 全局状态:
            全局状态["波动率分类"] = {}
        全局状态["波动率分类"].update({
            "分类": self.当前分类,
            "波动率": round(self.当前波动率 * 100, 2),
            "建议_下跌拦截": 建议.get("下跌拦截"),
            "建议_上涨拦截": 建议.get("上涨拦截"),
        })
        return {"允许买入": True, "质量分调整": 1.0, 
                "说明": f"波动率{self.当前波动率*100:.1f}%→{self.当前分类}"}
    
    def 获取当前建议(self) -> dict:
        建议 = self.阈值映射.get(self.当前分类, {})
        return {
            "分类": self.当前分类,
            "波动率": round(self.当前波动率 * 100, 2),
            "下跌拦截阈值": 建议.get("下跌拦截"),
            "上涨拦截阈值": 建议.get("上涨拦截"),
        }
    
    def 重置(self):
        self.收益率历史 = []
        self.前收盘 = None
        self.当前波动率 = 0.0
        self.当前分类 = "中波动"

if __name__ == "__main__":
    因子 = 波动率分类器()
    print("波动率分类器 自检 OK")
    价格列表 = [100, 105, 98, 110, 95, 108, 102, 115, 97, 112, 99, 118, 93, 120, 96, 125, 90, 130, 92, 135]
    for 价 in 价格列表:
        因子.每根K线处理({"前复权_收盘": 价}, {})
    建议 = 因子.获取当前建议()
    print(f"  高波动测试: 波动率={建议['波动率']}% 分类={建议['分类']} 阈值={建议['下跌拦截阈值']}/{建议['上涨拦截阈值']}")
    因子.重置()
    价格列表 = [100, 100.5, 101, 100.8, 101.2, 100.9, 101.5, 101.8, 102, 101.5, 102.2, 102.5, 102.8, 103, 103.2, 103.5, 103.8, 104, 104.2, 104.5]
    for 价 in 价格列表:
        因子.每根K线处理({"前复权_收盘": 价}, {})
    建议 = 因子.获取当前建议()
    print(f"  低波动测试: 波动率={建议['波动率']}% 分类={建议['分类']} 阈值={建议['下跌拦截阈值']}/{建议['上涨拦截阈值']}")
    print("\n✅ 自检完成")
