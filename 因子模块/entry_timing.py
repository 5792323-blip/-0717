# entry_timing.py — K线动量入场 (独立小程序)
# 大阳线(实体>0.7ATR)→开盘买入 / 中阳线→收盘价 / 小阳线→最高价

from 因子模块.因子基类 import 因子基类

class K线动量入场(因子基类):
    def __init__(self, 参数=None):
        super().__init__(参数)
        self.名称 = "K线动量入场"
        self.大阳线阈值 = self.参数.get('大阳线阈值', 0.7)
        self.中阳线阈值 = self.参数.get('中阳线阈值', 0.3)
    
    def 买入前检查(self, K线数据, 全局状态) -> dict:
        开盘 = K线数据.get('前复权_开盘', 0)
        收盘 = K线数据.get('前复权_收盘', 0)
        atr = K线数据.get('ATR_14', 0)
        if 开盘 <= 0 or 收盘 <= 0 or atr <= 0:
            return {"允许买入": True, "质量分调整": 1.0, "说明": "数据不足"}
        动量 = abs(收盘 - 开盘) / atr
        if 动量 > self.大阳线阈值 and 收盘 > 开盘:
            return {"允许买入": True, "质量分调整": 1.1, "说明": f"大阳线(动量={动量:.2f})→开盘"}
        if 动量 > self.中阳线阈值 and 收盘 > 开盘:
            return {"允许买入": True, "质量分调整": 1.0, "说明": f"中阳线(动量={动量:.2f})→收盘"}
        return {"允许买入": True, "质量分调整": 0.9, "说明": f"弱K线(动量={动量:.2f})→等最高"}
    
    def 重置(self): pass

if __name__ == "__main__":
    因子 = K线动量入场()
    print("K线动量入场 自检 OK")
    for 开盘, 收盘, 描述 in [(100,108,"大阳线"),(100,103,"中阳线"),(100,101,"小阳线")]:
        r = 因子.买入前检查({"前复权_开盘":开盘,"前复权_收盘":收盘,"前复权_最高":收盘+2,"前复权_最低":开盘-1,"ATR_14":5}, {})
        print(f"  {描述}: {r['说明']}")
