# total_control.py — 总仓位控制
# 功能: 控制整体仓位风险（单股上限、行业上限、总仓位上限）
#
# 用法:
#   from 仓位管理.total_control import 检查总仓位

def 检查总仓位(当前持仓数=0, 最大持仓=200, 总持仓金额=0, 
              总资金=20000000, 大盘系数=1.0):
    """
    检查总仓位是否超过限制
    
    传入:
        当前持仓数   - 当前持有多少只股票
        最大持仓     - 最多持有多少只，默认200
        总持仓金额   - 投入的总金额
        总资金       - 总资金
        大盘系数     - 0.2~1.0
    
    传出:
        {"允许买入": True/False, "剩余配额": 金额, "理由": "..."}
    """
    
    目标仓位比例 = 0.98 * 大盘系数
    最大可用 = 总资金 * 目标仓位比例
    
    剩余配额 = 最大可用 - 总持仓金额
    剩余持仓数 = 最大持仓 - 当前持仓数
    
    if 剩余配额 <= 0:
        return {"允许买入": False, "剩余配额": 0, "理由": f"总仓位已满(持仓{总持仓金额:.0f}≥目标{最大可用:.0f})"}
    
    if 剩余持仓数 <= 0:
        return {"允许买入": False, "剩余配额": 0, "理由": f"持仓数已满({当前持仓数}≥{最大持仓})"}
    
    return {"允许买入": True, "剩余配额": 剩余配额, "剩余持仓数": 剩余持仓数, "理由": ""}


if __name__ == "__main__":
    print("=" * 40)
    print("总仓位控制 — 自检测试")
    print("=" * 40)
    
    结果 = 检查总仓位(50, 200, 5000000, 20000000, 1.0)
    print(f"  允许买入: {结果['允许买入']}, 剩余配额: {结果['剩余配额']:.0f}")
    
    结果2 = 检查总仓位(200, 200, 19600000, 20000000, 1.0)
    print(f"  满仓测试: 允许买入: {结果2['允许买入']}, 理由: {结果2['理由']}")
    
    print("\n✅ 总仓位控制自检完成")
