# position_sizing.py — 单只仓位计算
# 功能: 根据信号质量、大盘状态、波动率，计算应该买多少
# 仓位 = 基准仓位 × 信号质量分 × 大盘系数 × 波动率调整
#
# 用法:
#   from 仓位管理.position_sizing import 计算仓位

def 计算仓位(基准金额=200000, 信号质量分=1.0, 大盘系数=1.0, 
             波动率调整=1.0, 单只上限=2000000, 当前现金=20000000):
    """
    计算单只股票的买入金额
    
    传入:
        基准金额    - 基础仓位金额，默认20万
        信号质量分  - 0~1 (从信号质量评分.py获取)
        大盘系数    - 0.2~1.0 (从大盘状态判断.py获取)
        波动率调整  - ATR调整系数
        单只上限    - 最多不能超过多少，默认200万(10%)
        当前现金    - 当前可用现金
    
    传出:
        (买入金额, 买入比例)
    """
    
    金额 = 基准金额 * 信号质量分 * 大盘系数 * 波动率调整
    
    # 上限控制
    金额 = min(金额, 单只上限)
    金额 = min(金额, 当前现金 * 0.2)  # 单次不超过现金20%
    金额 = max(金额, 0)
    
    return 金额, 金额 / 20000000


