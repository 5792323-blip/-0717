#!/usr/bin/env python3
"""从v3台账导出一级行业历史评分的待采集指标清单。"""
import os
import pandas as pd

根目录=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
工作簿=os.path.join(根目录,"基本面","全行业景气度量化跟踪体系_v3_全行业核心驱动版.xlsx")
输出=os.path.join(根目录,"基本面","历史数据","行业历史指标采集清单.csv")
一级行业={"农林牧渔","基础化工","钢铁","有色金属","电子","汽车","家用电器","食品饮料","纺织服饰","轻工制造","医药生物","公用事业","交通运输","房地产","商贸零售","社会服务","综合","建筑材料","建筑装饰","电力设备","机械设备","国防军工","计算机","传媒","通信","银行","非银金融","煤炭","石油石化","环保","美容护理"}

data=pd.read_excel(工作簿,sheet_name="指标更新台账_v3")
data=data[data["行业"].isin(一级行业)].copy()
data["历史频率"]="月度；季频指标按实际披露日生效"
data["历史状态"]="待采集"
data["最早回测需要"]="2020-01-01"
data.loc[data["角色"].eq("核心先行"),"历史优先级"]="P0"
data.loc[~data["角色"].eq("核心先行"),"历史优先级"]="P1"
cols=["行业","指标键","层级","指标名称","建议权重","数据来源","评分口径","角色","历史优先级","历史频率","最早回测需要","历史状态","更新备注"]
data[cols].sort_values(["历史优先级","行业","指标键"]).to_csv(输出,index=False,encoding="utf-8-sig")
print(f"已生成 {len(data)} 项历史采集清单: {输出}")
