# consecutive_loss_filter.py — 连续亏损暂停因子
# 功能: 连续亏损N次后暂停M根K线

def 检查(哨兵价类型, K线数据, 状态, 配置):
    """
    检查是否处于连续亏损后的冷却期
    
    传入:
        哨兵价类型 - 哨兵价形成类型
        K线数据   - 当前K线数据
        状态      - 公共状态（连续亏损次数、冷却剩余）
        配置      - YAML配置
    
    传出:
        {"通过": True/False, "原因": "..."}
    """
    连续亏损 = 状态.get('连续亏损次数', 0)
    冷却剩余 = 状态.get('冷却期剩余K线', 0)
    上限 = 配置.get('连续亏损上限', 3)
    
    if 冷却剩余 > 0:
        return {"通过": False, "原因": f"冷却期剩余{冷却剩余}根K线"}
    
    if 连续亏损 >= 上限:
        return {"通过": False, "原因": f"连续亏损{连续亏损}次, 需冷却{配置.get('冷却K线数',10)}根"}
    
    return {"通过": True, "原因": f"连续亏损{连续亏损}次, 通过"}
