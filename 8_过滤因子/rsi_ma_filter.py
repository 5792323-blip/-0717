# rsi_ma_filter.py - RSI_MA假信号过滤因子
# 功能: 仅过滤RSI上穿均线信号，当MA突破前N根最高值时暂缓买入
# 理由: MA创新高说明Rsi已在高位，此时买入追涨风险高
# 配置项: 检查K线数

def 检查(哨兵价类型, K线数据, 状态, 配置):
    """
    检查RSI上穿均线信号是否为假信号
    
    传入:
        哨兵价类型 - 当前哨兵价的形成类型
        K线数据   - 当前K线数据
        状态      - 规则执行器的公共状态字典（含MA序列）
        配置      - 该因子的YAML配置
    
    传出:
        {"通过": True, "原因": "..."}
        {"通过": False, "原因": "..."}
    """
    # 仅对RSI上穿均线信号生效
    if 哨兵价类型 != 'RSI上穿均线':
        return {"通过": True, "原因": "非均线信号, 通过"}
    
    MA序列 = 状态.get('MA序列', [])
    对比数 = 配置.get('检查K线数', 5)
    
    if len(MA序列) < 对比数 + 2:
        return {"通过": True, "原因": f"MA数据不足({len(MA序列)}<{对比数+2}), 通过"}
    
    MA_now = MA序列[-1]
    MA_max_prev = max(MA序列[-(对比数+1):-1])
    
    if MA_now > MA_max_prev:
        return {
            "通过": False,
            "原因": f"MA({MA_now:.1f})突破前{对比数}根最高({MA_max_prev:.1f}), 暂缓买入"
        }
    
    return {
        "通过": True,
        "原因": f"MA({MA_now:.1f})未突破前{对比数}根最高, 通过"
    }
