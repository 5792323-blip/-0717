# quality_score_filter.py — 信号质量分过滤因子
# 功能: 信号质量分低于阈值时不买

def 检查(哨兵价类型, K线数据, 状态, 配置):
    """
    检查信号质量分是否达标
    
    传入:
        哨兵价类型 - 哨兵价形成时的上穿类型
        K线数据   - 当前K线数据
        状态      - 已计算好的信号质量分
        配置      - YAML配置
    
    传出:
        {"通过": True/False, "原因": "..."}
    """
    质量分 = 状态.get('信号质量分', 0)
    最低分 = 配置.get('最低质量分', 0.3)
    
    if 质量分 < 最低分:
        return {"通过": False, "原因": f"质量分{质量分:.2f}<{最低分}, 拦截"}
    
    return {"通过": True, "原因": f"质量分{质量分:.2f}, 通过"}
