# ma_direction_filter.py — MA方向过滤因子
# 功能: MA斜率拦截（默认）或 二元方向过滤
#       斜率拦截: MA斜率 < 下阈值(默认-1.5) 或 MA斜率 > 上阈值(默认+1.5) 时拦截
#       二元方向: MA上升/下降 → 禁止买入
# 配置项: 过滤模式, 斜率下阈值, 斜率上阈值, 禁止方向, MA对比K线数

def 检查(哨兵价类型, K线数据, 状态, 配置):
    """
    检查MA方向是否符合买入条件
    
    传入:
        哨兵价类型 - 当前哨兵价的形成类型
        K线数据   - 当前K线数据
        状态      - 规则执行器的公共状态字典
        配置      - 该因子的YAML配置
    
    传出:
        {"通过": True, "原因": "..."}
        {"通过": False, "原因": "..."}
    """
    MA序列 = 状态.get('MA序列', [])
    
    过滤模式 = 配置.get('过滤模式', '斜率拦截')
    
    if 过滤模式 == '斜率拦截':
        return _斜率拦截_检查(MA序列, 配置)
    else:
        return _二元方向_检查(MA序列, 配置)


def _斜率拦截_检查(MA序列, 配置):
    """
    斜率拦截模式: MA斜率 < 下阈值 或 MA斜率 > 上阈值 时拦截
    """
    对比数 = 配置.get('MA对比K线数', 5)
    下阈值 = 配置.get('斜率下阈值', -1.5)
    上阈值 = 配置.get('斜率上阈值', 1.5)
    
    if len(MA序列) < 对比数 + 1:
        return {"通过": True, "原因": "MA数据不足, 通过"}
    
    # 斜率 = (最新MA - 前N根MA) / N
    MA最新 = MA序列[-1]
    MA前N = MA序列[-(对比数 + 1)]
    斜率 = (MA最新 - MA前N) / 对比数
    
    if 斜率 < 下阈值:
        return {
            "通过": False,
            "原因": f"MA斜率{斜率:.2f}<{下阈值}, 大幅下跌拦截"
        }
    
    if 斜率 > 上阈值:
        return {
            "通过": False,
            "原因": f"MA斜率{斜率:.2f}>{上阈值}, 大幅追涨拦截"
        }
    
    return {
        "通过": True,
        "原因": f"MA斜率{斜率:.2f}, 通过"
    }


def _二元方向_检查(MA序列, 配置):
    """
    原始模式: 根据MA上升/下降方向拦截
    """
    对比数 = 配置.get('MA对比K线数', 5)
    
    if len(MA序列) < 对比数 + 1:
        return {"通过": True, "原因": "MA数据不足, 通过"}
    
    MA最新 = MA序列[-1]
    MA前N = MA序列[-(对比数 + 1)]
    
    禁止方向 = 配置.get('禁止方向', '上升')
    
    if 禁止方向 == '上升' and MA最新 > MA前N:
        return {"通过": False, "原因": f"MA上升{MA前N:.1f}→{MA最新:.1f}, 拦截"}
    
    if 禁止方向 == '下降' and MA最新 < MA前N:
        return {"通过": False, "原因": f"MA下降{MA前N:.1f}→{MA最新:.1f}, 拦截"}
    
    return {"通过": True, "原因": f"MA{'↑' if MA最新>MA前N else '↓'}, 通过"}
