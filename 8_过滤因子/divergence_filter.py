# divergence_filter.py — RSI背离检测过滤因子
# 功能: 顶背离暂停买入，底背离加强信号（通过质量分）
# 配置项: 顶背离拦截启用, 检查顺序

def 检查(哨兵价类型, K线数据, 状态, 配置):
    """
    检查是否出现顶背离/底背离
    
    传入:
        哨兵价类型 - 当前哨兵价的形成类型
        K线数据   - 当前K线数据
        状态      - 规则执行器的公共状态字典（含 有底背离, 有顶背离）
        配置      - 该因子的YAML配置
    
    传出:
        {"通过": True, "原因": "..."}
        {"通过": False, "原因": "..."}
    """
    有顶背离 = 状态.get('有顶背离', False)
    有底背离 = 状态.get('有底背离', False)
    顶背离拦截 = 配置.get('顶背离拦截', True)
    
    # 顶背离 → 拦截买入
    if 有顶背离 and 顶背离拦截:
        return {"通过": False, "原因": "顶背离, 暂停买入"}
    
    # 底背离 → 通过（加强信号由质量分处理）
    if 有底背离:
        return {"通过": True, "原因": "底背离, 信号加强, 通过"}
    
    return {"通过": True, "原因": "无背离, 通过"}
