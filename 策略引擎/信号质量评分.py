# 信号质量评分.py — 给买入信号打分
# 功能: 根据多个维度，给每个信号打 0~1 分
# 用途: 分数越高 → 仓位越重
#
# 评分维度: 基础分 × 背离调整 × 大盘系数 × 波动率调整
#
# 用法:
#   from 策略引擎.信号质量评分 import 评分

import pandas as pd
import numpy as np


def 评分(信号类型, 大盘状态="震荡模式", 有底背离=False, 有顶背离=False, 波动率调整=1.0):
    """
    给买入信号打综合质量分
    
    传入:
        信号类型    - "RSI上穿20" / "RSI上穿30" / "RSI上穿均线" / "RSI上穿70"
        大盘状态    - "进攻模式" / "震荡模式" / "防守模式" / "收缩模式"
        有底背离    - 是否出现底背离
        有顶背离    - 是否出现顶背离
        波动率调整  - ATR调整系数
    
    传出:
        综合质量分 (0~1)
        评分明细 (字典)
    """
    
    # 1. 基础分 — 按信号类型
    基础分对照 = {
        "RSI上穿20": 1.0,     # 极端超卖，最有价值的信号
        "RSI上穿30": 0.7,     # 超卖反弹
        "RSI上穿均线": 0.4,   # 均线突破
        "RSI上穿70": 0.2,     # 追涨，风险较高
    }
    
    基础分 = 基础分对照.get(信号类型, 0.3)
    
    # 2. 背离调整
    背离调整 = 1.0
    
    if 有底背离:
        背离调整 *= 1.2       # 底背离 → 加强信号
    if 有顶背离:
        if 信号类型 == "RSI上穿70":
            背离调整 = 0.0    # 顶背离+追涨 → 禁止买入
        else:
            背离调整 *= 0.3   # 顶背离 → 大幅减分
    
    # 3. 大盘状态调整
    大盘调整对照 = {
        "进攻模式": 1.0,      # 大盘好，正常做
        "震荡模式": 0.6,      # 大盘震荡，打折
        "防守模式": 0.3,      # 大盘差，轻仓
        "收缩模式": 0.5,      # 高波动，保守
    }
    
    大盘调整 = 大盘调整对照.get(大盘状态, 0.5)
    
    # 交叉限制: 防守模式下只允许 RSI上穿20
    if 大盘状态 == "防守模式" and 信号类型 != "RSI上穿20":
        大盘调整 = 0.0
    
    # 4. 综合计算
    综合分 = 基础分 * 背离调整 * 大盘调整 * 波动率调整
    
    # 确保在 0~1 范围内
    综合分 = max(0.0, min(1.0, 综合分))
    
    评分明细 = {
        "信号类型": 信号类型,
        "基础分": 基础分,
        "背离调整": 背离调整,
        "大盘调整": 大盘调整,
        "波动率调整": 波动率调整,
        "综合分": 综合分,
    }
    
    return 综合分, 评分明细


