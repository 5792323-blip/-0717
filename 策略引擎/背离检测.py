# 背离检测.py — 检测顶背离和底背离
# 功能: 比较价格走势和RSI走势，判断有没有背离
#
# 顶背离: 价格创新高，RSI没创新高 → 可能要跌
# 底背离: 价格创新低，RSI没创新低 → 可能要涨
#
# 用法:
#   from 策略引擎.背离检测 import 检测顶背离, 检测底背离

import pandas as pd
import numpy as np


def 检测背离(价格序列, RSI序列, 查看K线数=60):
    """
    同时检测顶背离和底背离
    
    传入:
        价格序列  - 前复权收盘价
        RSI序列   - RSI数值
        查看K线数 - 看过去多少根K线做对比，默认60
    
    传出:
        字典: {"顶背离": True/False, "底背离": True/False, "强度": "轻/中/重"}
    """
    
    结果 = {"顶背离": False, "底背离": False, "强度": "无"}
    
    if len(价格序列) < 查看K线数:
        return 结果
    
    最近价格 = 价格序列.iloc[-查看K线数:].values
    最近RSI = RSI序列.iloc[-查看K线数:].values
    
    # 找最高价和对应的RSI
    价格最高位置 = np.argmax(最近价格)
    价格最高值 = 最近价格[价格最高位置]
    当时RSI值 = 最近RSI[价格最高位置]
    
    # 当前价格和RSI
    当前价格 = 最近价格[-1]
    当前RSI = 最近RSI[-1]
    
    # --- 顶背离 ---
    # 条件: 价格创新高 但 RSI没创新高
    if 当前价格 >= 价格最高值 * 0.995:  # 当前价格接近或超过前期高点
        if 当前RSI < 当时RSI值 - 2:     # RSI显著低于前期高点
            结果["顶背离"] = True
            # 判断背离强度
            rsi差距 = 当时RSI值 - 当前RSI
            if rsi差距 > 10:
                结果["强度"] = "重"
            elif rsi差距 > 5:
                结果["强度"] = "中"
            else:
                结果["强度"] = "轻"
    
    # --- 底背离 ---
    价格最低位置 = np.argmin(最近价格)
    价格最低值 = 最近价格[价格最低位置]
    当时RSI_底 = 最近RSI[价格最低位置]
    
    if 当前价格 <= 价格最低值 * 1.005:  # 当前价格接近或低于前期低点
        if 当前RSI > 当时RSI_底 + 2:     # RSI显著高于前期低点
            结果["底背离"] = True
    
    return 结果


def 检测顶背离(价格序列, RSI序列, 查看K线数=60):
    """
    专门检测顶背离
    价格创新高，RSI没创新高 → 动能减弱，可能到顶了
    """
    结果 = 检测背离(价格序列, RSI序列, 查看K线数)
    return 结果["顶背离"]


def 检测底背离(价格序列, RSI序列, 查看K线数=60):
    """
    专门检测底背离
    价格创新低，RSI没创新低 → 动能转强，可能到底了
    """
    结果 = 检测背离(价格序列, RSI序列, 查看K线数)
    return 结果["底背离"]


