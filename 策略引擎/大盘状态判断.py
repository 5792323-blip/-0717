# 大盘状态判断.py — 判断当前市场处于什么状态
# 功能: 根据HS300指数，判断当前是进攻/震荡/防守/收缩
# 用途: 不同的市场状态，策略做不同的调整
#
# 四种状态:
#   进攻模式 🟢 - 大盘趋势向上 → 目标仓位80-98%，所有信号正常执行
#   震荡模式 🟡 - 不上不下     → 目标仓位30-50%，信号打5-7折
#   防守模式 🔴 - 大盘趋势向下 → 目标仓位10-20%，仅cross_20可买
#   收缩模式 ⚠️ - 波动率飙升   → 收紧止损，降低基准仓位
#
# 用法:
#   from 策略引擎.大盘状态判断 import 判断大盘状态

import pandas as pd
import numpy as np


def 判断大盘状态(大盘收盘价=None, 大盘最高价=None, 大盘最低价=None, 
               大盘日期=None, 市场平均ATR=None, 前20日ATR=None):
    """
    判断当前大盘处于哪种状态
    
    传入:
        大盘收盘价     - HS300收盘价序列
        大盘最高价     - HS300最高价序列 (可选)
        大盘最低价     - HS300最低价序列 (可选)
        大盘日期       - 日期列表 (可选)
        市场平均ATR    - 当前市场平均ATR (可选)
        前20日ATR      - 前20日市场平均ATR (可选)
    
    传出:
        状态名称: "进攻模式" / "震荡模式" / "防守模式" / "收缩模式"
        状态明细: 包含判断依据的字典
    """
    
    状态 = "震荡模式"
    明细理由 = []
    
    if 大盘收盘价 is None or len(大盘收盘价) < 120:
        return "震荡模式", {"理由": "大盘数据不足(需要至少120根K线)"}
    
    价格 = pd.Series(大盘收盘价)
    
    # 计算均线 — 变量名不能用数字开头
    均线_120 = 价格.rolling(window=120, min_periods=120).mean()
    均线_20 = 价格.rolling(window=20, min_periods=20).mean()
    
    当前价格 = 价格.iloc[-1]
    当前均线_120 = 均线_120.iloc[-1]
    当前均线_20 = 均线_20.iloc[-1]
    
    # 均线_20斜率
    if len(价格) >= 25:
        前5日均线_20 = 均线_20.iloc[-5]
        斜率_20 = (当前均线_20 - 前5日均线_20) / 前5日均线_20
    else:
        斜率_20 = 0
    
    # 判断进攻还是防守
    在120线上方 = 当前价格 > 当前均线_120 * 1.03
    在120线下方 = 当前价格 < 当前均线_120 * 0.97
    短期向上 = 斜率_20 > 0.002
    短期向下 = 斜率_20 < -0.002
    
    if 在120线上方 and 短期向上:
        状态 = "进攻模式"
        明细理由 = [f"大盘在120日线({当前均线_120:.0f})上方", f"20日线向上(斜率{斜率_20:.4f})"]
    elif 在120线下方 and 短期向下:
        状态 = "防守模式"
        明细理由 = [f"大盘在120日线({当前均线_120:.0f})下方", f"20日线向下(斜率{斜率_20:.4f})"]
    else:
        状态 = "震荡模式"
        明细理由 = [f"大盘在120日线({当前均线_120:.0f})附近波动"]
    
    # 检查收缩模式（高波动覆盖其他状态）
    if 市场平均ATR is not None and 前20日ATR is not None:
        if 前20日ATR > 0 and 市场平均ATR > 前20日ATR * 1.5:
            状态 = "收缩模式"
            明细理由 = [f"市场波动率飙升(ATR {市场平均ATR:.2f} > {前20日ATR:.2f}×1.5)"]
    
    明细 = {
        "状态": 状态,
        "当前价格": 当前价格,
        "均线_120": 当前均线_120,
        "均线_20": 当前均线_20,
        "斜率_20": 斜率_20,
        "理由": "; ".join(明细理由)
    }
    
    return 状态, 明细


