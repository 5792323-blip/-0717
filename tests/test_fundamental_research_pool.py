import pandas as pd

from 基本面.生成基本面研究池 import 生成


def test_pool_excludes_hard_risk_and_limits_candidates():
    score = pd.DataFrame([
        {"股票代码": "600519", "评分日期": "2026-07-28", "总分": 80, "置信度": .5, "硬风险": ""},
        {"股票代码": "000001", "评分日期": "2026-07-28", "总分": 90, "置信度": .9, "硬风险": "重大资金占用"},
        {"股票代码": "000002", "评分日期": "2026-07-28", "总分": 65, "置信度": .3, "硬风险": ""},
    ])
    snapshot = pd.DataFrame([
        {"股票代码": "600519", "归母净利润": 10, "经营现金流净额": 12},
        {"股票代码": "000001", "归母净利润": 10, "经营现金流净额": 12},
        {"股票代码": "000002", "归母净利润": 10, "经营现金流净额": 12},
    ])
    result = 生成(score, snapshot, limit=2)
    assert result.loc[result["股票代码"] == "000001", "研究分层"].iloc[0] == "硬风险排除"
    assert result["入选研究池"].sum() == 2
