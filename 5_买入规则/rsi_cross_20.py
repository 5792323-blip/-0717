# rsi_cross_20.py — RSI上穿20买入规则
# 功能: 检查RSI是否从20以下上穿到20以上
# 这是"极端超卖反弹"信号，优先级最高
#
# 用法:
#   from 买入规则.rsi_cross_20 import 检查
#   结果 = 检查(当前RSI, 上一根RSI)

def 检查(当前RSI, 上一根RSI, **kwargs):
    """
    检查RSI上穿20信号
    
    传入:
        当前RSI  - 当前这根K线的RSI值
        上一根RSI - 上一根K线的RSI值
    
    传出:
        字典: {"触发": True/False, "类型": "信号名称", "优先级": 数字}
    """
    
    if 上一根RSI <= 20 and 当前RSI > 20:
        return {
            "触发": True,
            "类型": "RSI上穿20",
            "优先级": 0,       # 0=最高
            "基础质量分": 1.0   # 最好的信号
        }
    
    return {"触发": False}


if __name__ == "__main__":
    print("=" * 40)
    print("RSI上穿20 — 自检测试")
    print("=" * 40)
    
    # 测试用例
    测试集 = [
        (19, 21, True),    # 从19上穿到21 → 触发
        (21, 22, False),   # 已经在20以上 → 不触发
        (18, 19, False),   # 还在20以下 → 不触发
        (20, 21, False),   # 从20上穿 → 严格来说不算"下穿20再上穿" 
        (15, 20.5, True),  # 从15上穿到20.5 → 触发
    ]
    
    print(f"{'上一个RSI':<10} {'当前RSI':<10} {'预期':<8} {'实际':<8} {'结果':<8}")
    print("-" * 50)
    for 上一个, 当前, 预期 in 测试集:
        结果 = 检查(当前, 上一个)
        实际触发 = 结果["触发"]
        是否正确 = "✅" if 实际触发 == 预期 else "❌"
        print(f"{上一个:<10} {当前:<10} {str(预期):<8} {str(实际触发):<8} {是否正确}")
    
    print("\n✅ RSI上穿20自检完成")
